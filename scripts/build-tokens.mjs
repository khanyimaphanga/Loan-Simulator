#!/usr/bin/env node
/**
 * Design token pipeline: tokens/tokens.json (W3C DTCG) -> CSS custom properties + typed TS module.
 *
 *  primitive.*  -> --cap-<path>         (raw palette; never used directly by components)
 *  semantic.*   -> --<path>             (themeable; light on :root, dark via media query + [data-theme])
 *  component.*  -> --<path>             (component-scoped decisions)
 *
 * Aliases like "{primitive.color.blue.500}" resolve to var(--cap-color-blue-500) so the cascade stays live.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'));
const outDir = resolve(root, 'client/src/styles');

const isToken = (node) => node && typeof node === 'object' && '$value' in node;

function flatten(node, path = [], out = []) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (isToken(child)) out.push({ path: [...path, key], value: child.$value });
    else if (child && typeof child === 'object') flatten(child, [...path, key], out);
  }
  return out;
}

const cssName = (path) => {
  const [tier, ...rest] = path;
  return tier === 'primitive' ? `--cap-${rest.join('-')}` : `--${rest.join('-')}`;
};

const lookup = (path) => path.split('.').reduce((n, k) => n?.[k], tokens);

function resolveAlias(value, { asVar }) {
  if (typeof value !== 'string') return String(value);
  return value.replace(/\{([^}]+)\}/g, (_, ref) => {
    const target = lookup(ref);
    if (!isToken(target)) throw new Error(`Unresolved token alias {${ref}}`);
    return asVar ? `var(${cssName(ref.split('.'))})` : resolveAlias(target.$value, { asVar });
  });
}

const decl = (list, strip = 0) =>
  list
    .map(({ path, value }) => `  ${cssName([path[0], ...path.slice(1 + strip)])}: ${resolveAlias(value, { asVar: true })};`)
    .join('\n');

const primitives = flatten(tokens.primitive, ['primitive']);
const light = flatten(tokens.semantic.light, ['semantic', 'light']);
const dark = flatten(tokens.semantic.dark, ['semantic', 'dark']);
const components = flatten(tokens.component, ['component', 'component']);

const css = `/* AUTO-GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */

:root {
${decl(primitives)}
}

:root {
  color-scheme: light;
${decl(light, 1)}
${decl(components, 1)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${decl(dark, 1).replace(/^/gm, '  ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${decl(dark, 1)}
}
`;

// Typed JS export (resolved hex values) for places CSS vars can't reach, e.g. <meta name="theme-color">.
const resolvedTheme = (list) =>
  Object.fromEntries(list.map(({ path, value }) => [path.slice(2).join('.'), resolveAlias(value, { asVar: false })]));

const ts = `/* AUTO-GENERATED by scripts/build-tokens.mjs. Do not edit by hand. */
export const tokens = ${JSON.stringify({ light: resolvedTheme(light), dark: resolvedTheme(dark) }, null, 2)} as const;

export type ThemeName = keyof typeof tokens;
export type SemanticToken = keyof typeof tokens.light;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'tokens.css'), css);
writeFileSync(resolve(outDir, 'tokens.ts'), ts);
console.log(`✓ tokens: ${primitives.length} primitive, ${light.length} semantic, ${components.length} component -> client/src/styles`);
